function copyPhase4Source() {
  const code = document.getElementById("phase4CodeOutput")?.textContent || "";
  if (!code || code.startsWith("//")) return;
  navigator.clipboard.writeText(code).then(() => {
    const btn = document.getElementById("copyCSourceBtn");
    if (btn) {
      const orig = btn.textContent;
      btn.textContent = "Copied!";
      setTimeout(() => { btn.textContent = orig; }, 1500);
    }
  });
}

function downloadPhase4Source() {
  const code = document.getElementById("phase4CodeOutput")?.textContent || "";
  if (!code || code.startsWith("//")) return;
  const blob = new Blob([code], { type: "text/x-csrc" });
  const url = window.URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.style.display = "none";
  a.href = url;
  a.download = "sched_ext_policy.c";
  document.body.appendChild(a);
  a.click();
  setTimeout(() => {
    window.URL.revokeObjectURL(url);
    a.remove();
  }, 1000);
}

async function emitPhase4Source() {
  const source = document.getElementById("mainCodeEditor")?.value?.trim();
  const output = document.getElementById("phase4CodeOutput");
  const status = document.getElementById("phase4EmitStatus");
  const badge = document.getElementById("phase4CodeStatus");
  const copyBtn = document.getElementById("copyCSourceBtn");
  const downloadBtn = document.getElementById("downloadCSourceBtn");

  if (!source || !output) return;
  // Never leave an earlier policy's C visible while a new request is pending
  // or after the backend rejects unsupported runtime semantics.
  output.textContent = "";
  if (copyBtn) copyBtn.disabled = true;
  if (downloadBtn) downloadBtn.disabled = true;
  output.textContent = "Generating sched_ext C code...";
  if (status) status.textContent = "Compiling PolicyLang IR and lowering to sched_ext struct_ops C skeleton...";
  if (badge) { badge.textContent = "GENERATING"; badge.className = "badge badge-neutral"; }

  try {
    const res = await fetch("/api/codegen", {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({ source }),
    });
    const data = await res.json().catch(() => ({}));
    const unsupported = data.status === "UNSUPPORTED" || data.status_label === "UNSUPPORTED";
    if (unsupported) {
      const reasons = [...(data.unsupported_semantics || []), ...(data.limitations || [])];
      output.textContent = "No sched_ext C source emitted.";
      if (status) status.textContent = `Unsupported policy: ${reasons.join("; ") || data.detail || "backend capability is unavailable"}`;
      if (badge) { badge.textContent = "UNSUPPORTED"; badge.className = "badge badge-amber"; }
      return;
    }
    if (!res.ok) throw new Error(data.detail || data.message || await apiErrorMessage(res));
    if (!data.c_code) throw new Error("backend returned an empty source payload");
    output.textContent = data.c_code || "No source emitted.";
    if (status) status.textContent = `sched_ext struct_ops C source generated successfully from active PolicyLang IR.`;
    if (badge) {
      // A deterministic source emitter can succeed even when the returned
      // metadata lists runtime/build limitations. Keep those limitations in
      // the generated source response instead of presenting emission as unsupported.
      badge.textContent = data.c_code ? "EMISSION_SUCCEEDED (BUILD_NOT_RUN)" : (data.status_label || "EMISSION_FAILED");
      badge.className = "badge badge-green";
    }
    if (copyBtn) copyBtn.disabled = false;
    if (downloadBtn) downloadBtn.disabled = false;
  } catch (err) {
    output.textContent = "No sched_ext C source emitted.";
    if (status) status.textContent = `Source generation failed: ${err.message}`;
    if (badge) { badge.textContent = "FAILED"; badge.className = "badge badge-red"; }
    if (copyBtn) copyBtn.disabled = true;
    if (downloadBtn) downloadBtn.disabled = true;
  }
}

