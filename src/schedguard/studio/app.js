async function runPhase3Repair() {
  const source = document.getElementById("repairSource")?.value.trim();
  // Always use the deterministic heuristic — Template/Raw options have been removed
  const feedback = "heuristic";
  const status = document.getElementById("repairStatus");
  const diffBox = document.getElementById("repairDiffBox");
  const applyBtn = document.getElementById("repairApplyBtn");
  const copyBtn = document.getElementById("repairCopyBtn");

  if (!source) {
    status.textContent = "Enter PolicyLang source first.";
    status.className = "phase3-status status-warning";
    return;
  }
  status.textContent = "Classifying violated guarantees and executing bounded deterministic repair loop…";
  status.className = "phase3-status status-running";

  try {
    const classificationResponse = await fetch("/api/classify", {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({ source }),
    });
    const classification = await phase3ResponseJson(classificationResponse);

    const repairResponse = await fetch("/api/repair", {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({ source, feedback }),
    });
    const repair = await phase3ResponseJson(repairResponse);

    // Render classifications
    const classifHtml =
      `<div class="status-row"><span>Overall Status</span><strong>${phase3Escape(classification.status)}</strong></div>` +
      (classification.verdicts || []).map(v =>
        `<div class="verdict-row"><strong class="verdict-${String(v.status).toLowerCase()}">${phase3Escape(v.status)}</strong><span>${phase3Escape(v.guarantee)}</span><small>${phase3Escape(v.replay || "")}</small></div>`
      ).join("") +
      (classification.classifications || []).map(c =>
        `<div class="cause-box"><strong>Classified Cause: ${phase3Escape(c.cause)}</strong><p>${phase3Escape(c.explanation)}</p><small>${phase3Escape(JSON.stringify(c.evidence || {}))}</small></div>`
      ).join("");

    document.getElementById("repairClassifications").innerHTML = classifHtml || "No guarantees declared.";

    // Render iterations
    document.getElementById("repairIterations").innerHTML =
      (repair.iterations || []).map((it, idx) =>
        `<div class="verdict-row"><strong>Round ${it.iteration || idx}: ${phase3Escape(it.status)}</strong><span>Cause: ${phase3Escape(it.cause || "—")}</span><small>${phase3Escape(it.message || (it.verdicts?.map(v => `${v.guarantee}: ${v.status}`).join(", ") || ""))}</small></div>`
      ).join("") || "No iterations recorded.";

    // Render repaired source
    document.getElementById("repairSourceOutput").textContent = repair.source || "No repaired source.";

    // Render concrete diff
    if (diffBox) {
      if (repair.success && repair.source && repair.source !== source) {
        diffBox.innerHTML = generateSimpleDiff(source, repair.source);
        diffBox.classList.remove("hidden");
      } else if (repair.success) {
        diffBox.innerHTML = '<div class="diff-line-same">Policy already satisfies every declared guarantee; no source modification was necessary.</div>';
        diffBox.classList.remove("hidden");
      } else {
        const last = (repair.iterations || [])[repair.iterations?.length - 1] || {};
        const reason = last.message || "No verified repair was produced.";
        diffBox.innerHTML = `<div class="diff-line-removed">Repair not accepted: ${phase3Escape(reason)}. The original source is preserved.</div>`;
        diffBox.classList.remove("hidden");
      }
    }

    if (copyBtn) copyBtn.disabled = !repair.source;
    if (applyBtn) applyBtn.disabled = !repair.source || !repair.success;

    if (repair.success) {
      status.textContent = "Verified repair reached: all guarantees mathematically proven safe by Z3 SMT solver.";
      status.className = "phase3-status status-success";
    } else {
      const last = (repair.iterations || [])[repair.iterations?.length - 1] || {};
      status.textContent = `Repair not accepted: ${last.message || "bounded loop did not reach VERIFIED"}. Original source preserved.`;
      status.className = "phase3-status status-warning";
    }
  } catch (err) {
    status.textContent = `Repair failed: ${err.message}`;
    status.className = "phase3-status status-error";
    if (diffBox) diffBox.classList.add("hidden");
    if (applyBtn) applyBtn.disabled = true;
  }
}

