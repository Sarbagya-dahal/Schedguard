function phase3Escape(value) {
  return String(value ?? "").replace(/[&<>"']/g, ch => ({"&":"&amp;","<":"&lt;",">":"&gt;",'"':"&quot;","'":"&#39;"}[ch]));
}

function phase3Copy(text, button) {
  if (!text || text.startsWith("No ")) return;
  copyTextToClipboard(text).then(() => { if (button) { const old = button.textContent; button.textContent = "Copied"; setTimeout(() => button.textContent = old, 900); } });
}

async function copyTextToClipboard(value) {
  try {
    await navigator.clipboard.writeText(value);
    return true;
  } catch (_) {
    const area = document.createElement("textarea");
    area.value = value;
    area.setAttribute("readonly", "");
    area.style.position = "fixed";
    area.style.opacity = "0";
    document.body.appendChild(area);
    area.select();
    const copied = document.execCommand("copy");
    area.remove();
    if (!copied) throw new Error("clipboard access was unavailable");
    return true;
  }
}

async function phase3ResponseJson(response) {
  if (!response.ok) throw new Error(await apiErrorMessage(response));
  const text = await response.text();
  let data;
  try { data = text ? JSON.parse(text) : {}; }
  catch (_) { throw new Error(`Request failed (${response.status}); server returned a non-JSON response.`); }
  return data;
}

function generateSimpleDiff(oldText, newText) {
  if (!oldText || !newText || oldText === newText) return "";
  const oldLines = oldText.split("\n");
  const newLines = newText.split("\n");
  const diffHtml = ['<div class="diff-line-header">--- Original Submitted Source\n+++ Repaired PolicyLang Source</div>'];

  let i = 0, j = 0;
  while (i < oldLines.length || j < newLines.length) {
    if (i < oldLines.length && j < newLines.length && oldLines[i] === newLines[j]) {
      diffHtml.push(`<div class="diff-line-same">  ${phase3Escape(oldLines[i])}</div>`);
      i++; j++;
    } else if (j < newLines.length && (i >= oldLines.length || !oldLines.slice(i, i + 3).includes(newLines[j]))) {
      diffHtml.push(`<div class="diff-line-add">+ ${phase3Escape(newLines[j])}</div>`);
      j++;
    } else if (i < oldLines.length) {
      diffHtml.push(`<div class="diff-line-del">- ${phase3Escape(oldLines[i])}</div>`);
      i++;
    } else {
      break;
    }
  }
  return diffHtml.join("");
}

