/**
 * Render an AST value as an interactive tree.
 * depth=0 → root level (open), depth=1 → class/guarantee lists (open), depth>=2 → leaf properties (closed).
 */
function renderAstTree(value, label = "PolicyAST", depth = 0) {
  if (value === null || value === undefined) return "";
  if (typeof value !== "object") return `<span class="ast-value">${escapeHtml(String(value))}</span>`;
  const openByDefault = depth < 2;  // expand root + first-level groups; collapse deep leaves
  const children = Object.entries(value).map(([key, child]) => {
    if (Array.isArray(child)) {
      const items = child.map((item, i) => `<div class="ast-array-item"><span class="ast-key">[${i}]</span>${renderAstTree(item, key, depth + 2)}</div>`).join("");
      return `<details class="ast-node"${openByDefault ? " open" : ""}><summary>${escapeHtml(key)} <span class="ast-count">${child.length}</span></summary>${items}</details>`;
    }
    if (child && typeof child === "object") {
      return `<details class="ast-node"${openByDefault ? " open" : ""}><summary>${escapeHtml(key)}</summary>${renderAstTree(child, key, depth + 1)}</details>`;
    }
    return `<div class="ast-attribute"><span class="ast-key">${escapeHtml(key)}</span><span>${renderAstTree(child, key, depth + 1)}</span></div>`;
  }).join("");
  return `<div class="ast-object"><div class="ast-label">${escapeHtml(label)}</div>${children}</div>`;
}

