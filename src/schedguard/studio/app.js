async function downloadPdfForRun(runId) {
  if (!runId) {
    alert("A valid run ID is required to download a PDF report.");
    return;
  }
  const editorStatus = document.getElementById("editorStatusText");
  if (editorStatus) editorStatus.textContent = `Preparing academic PDF report for run ${runId}...`;

  try {
    const res = await fetch(`/api/run/${runId}/pdf`);
    if (!res.ok) {
      throw new Error(await apiErrorMessage(res));
    }
    const contentType = res.headers.get("content-type") || "";
    if (!contentType.includes("application/pdf")) {
      throw new Error(`Unexpected server response: content-type '${contentType}' is not a valid PDF.`);
    }
    const blob = await res.blob();
    if (blob.size === 0) {
      throw new Error("Server returned an empty PDF file.");
    }
    const url = window.URL.createObjectURL(blob);
    const a = document.createElement("a");
    a.style.display = "none";
    a.href = url;
    a.download = `schedguard_${appState.currentRunRecord?.policy_name || "policy"}_${runId}.pdf`;
    document.body.appendChild(a);
    a.click();
    setTimeout(() => {
      window.URL.revokeObjectURL(url);
      a.remove();
    }, 1000);
    if (editorStatus) editorStatus.textContent = `PDF report downloaded successfully for run ${runId}.`;
  } catch (err) {
    console.error("PDF download failed", err);
    if (editorStatus) editorStatus.textContent = `PDF download failed: ${err.message}`;
    alert("PDF download failed: " + err.message);
  }
}
window.downloadPdfForRun = downloadPdfForRun;

